// src/gen/api.d.ts: the OpenAPI contract as TypeScript, by openapi-typescript (the document is already in memory,
// so nothing is fetched or bundled from elsewhere).
import openapiTS, { astToString } from 'openapi-typescript';

export async function typesOf(openapi) {
  const ast = await openapiTS(structuredClone(openapi), { alphabetize: true, exportType: true });
  return `// Generated by webgen with openapi-typescript from openapi.json. Do not edit: run webgen again.\n${astToString(ast)}`;
}
