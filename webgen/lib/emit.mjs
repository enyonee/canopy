// The app model → the files of the generated project. Pure: a Map from a relative path to its text, the same for
// the same model, so a second run writes the same bytes. The design system and the screens are the template
// (webgen/template, copied as they are); what is particular to an app is generated here: the model, the typed
// endpoints over its OpenAPI, the route tree, the theme and the HTML shell.

const json = (v) => `${JSON.stringify(v, null, 2)}\n`;
const lit = (s) => JSON.stringify(s);
const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const HEADER = '// Generated by webgen from app.json and its OpenAPI contract. Do not edit: run webgen again.\n';

/** The exact versions the generated project builds with: one place, so every app gets the same. */
export const VERSIONS = {
  dependencies: {
    '@tanstack/react-query': '5.108.4', '@tanstack/react-router': '1.170.46', 'class-variance-authority': '0.7.1', clsx: '2.1.1',
    'lucide-react': '1.80.0', 'openapi-fetch': '0.17.0', 'radix-ui': '1.8.1', react: '19.3.1', 'react-dom': '19.3.1',
    'react-hook-form': '7.92.0', recharts: '3.11.1', sonner: '2.0.8', 'tailwind-merge': '3.7.1',
  },
  devDependencies: {
    '@tailwindcss/vite': '4.3.5', '@types/node': '22.20.7', '@types/react': '19.3.3', '@types/react-dom': '19.3.0', '@vitejs/plugin-react': '6.3.0',
    tailwindcss: '4.3.5', 'tw-animate-css': '1.4.0', typescript: '5.9.3', vite: '8.3.8',
  },
};

function packageJson(model) {
  return json({
    name: `${model.name}-web`, private: true, version: '0.0.0', type: 'module',
    description: `The front end of the Canopy app "${model.name}", generated by webgen from apps/${model.name}/app.json.`,
    scripts: {
      dev: 'vite', build: 'tsc --noEmit && vite build', typecheck: 'tsc --noEmit', preview: 'vite preview',
      'check:contract': `node ../../../webgen/check-contract.mjs ../app.json`,
    },
    dependencies: VERSIONS.dependencies, devDependencies: VERSIONS.devDependencies,
  });
}

function indexHtml(model) {
  const bg = model.theme.background || 'white', accent = model.theme.accent || '#4f46e5';
  return `<!doctype html>
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1.0, viewport-fit=cover" />
    <meta name="theme-color" content="${esc(accent)}" />
    <meta name="description" content="${esc(model.note || model.title)}" />
    <title>${esc(model.title)}</title>
    <link rel="icon" href="data:image/svg+xml,${encodeURIComponent(`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 32"><rect width="32" height="32" rx="8" fill="${accent}"/><text x="16" y="22" font-family="system-ui,sans-serif" font-size="18" font-weight="700" text-anchor="middle" fill="white">${model.title[0]}</text></svg>`)}" />
    <script>
      try { var t = localStorage.getItem('canopy-theme'); if (t === 'dark' || (t !== 'light' && matchMedia('(prefers-color-scheme: dark)').matches)) document.documentElement.classList.add('dark'); } catch (e) {}
    </script>
    <style>html { background: ${esc(bg)}; } html.dark { background: #15151c; }</style>
  </head>
  <body>
    <div id="root"></div>
    <noscript>${esc(model.title)} needs JavaScript. The plain version is at <a href="/admin">/admin</a>.</noscript>
    <script type="module" src="/src/main.tsx"></script>
  </body>
</html>
`;
}

function themeCss(model) {
  return `/* Generated by webgen from the graph's "theme". Do not edit: run webgen again. */
:root {
  --brand-bg: ${model.theme.background || 'white'};
  --brand: ${model.theme.accent || '#4f46e5'};
}
`;
}

function appTs(model) {
  return `${HEADER}import type { AppModel } from '@/lib/model';

export const app: AppModel = ${JSON.stringify(model, null, 2)};
`;
}

// The typed bindings of the screens' calls: each path is checked against src/gen/api.d.ts by tsc, so a contract
// that drops or renames a route fails the build instead of the screen.
function endpointsTs(model, openapi) {
  const has = (p, m) => Boolean(openapi.paths?.[p]?.[m]);
  const lines = [];
  for (const e of Object.values(model.entities)) {
    const base = `/api/${e.name}`, one = `${base}/{id}`;
    const step = (kind, names) => `{${names.filter((n) => has(`${one}/${kind}/${n}`, 'post')).map((n) =>
      `\n      ${lit(n)}: (id, body) => call(client.POST(${lit(`${one}/${kind}/${n}`)}, { params: { path: { id } }, body: body as B<${lit(`${one}/${kind}/${n}`)}> })) as Promise<Saved>,`).join('')}${names.length ? '\n    ' : ''}}`;
    const related = (e.detail.related || []).map((r) => r.entity).filter((c) => has(`${one}/related/${c}`, 'get'));
    lines.push(`  ${lit(e.name)}: {
    list: (query) => call(client.GET(${lit(base)}, { params: { query: query as Q<${lit(base)}> } })) as Promise<Page>,
    get: (id) => call(client.GET(${lit(one)}, { params: { path: { id } } })) as Promise<Row>,
    create: (body) => call(client.POST(${lit(base)}, { body: body as B<${lit(base)}> })) as Promise<Saved>,
    update: (id, body) => call(client.POST(${lit(one)}, { params: { path: { id } }, body: body as B<${lit(one)}> })) as Promise<Saved>,
    remove: (id) => call(client.POST(${lit(`${one}/delete`)}, { params: { path: { id } }, body: {} })) as Promise<{ ok: true; flash: string }>,
    go: ${step('go', (e.states?.transitions || []).map((t) => t.name))},
    action: ${step('action', e.actions.map((a) => a.name))},
    add: ${step('add', (e.detail.related || []).map((r) => r.entity))},
    related: {${related.map((c) => `\n      ${lit(c)}: (id, query) => call(client.GET(${lit(`${one}/related/${c}`)}, { params: { path: { id }, query: query as Q<${lit(`${one}/related/${c}`)}> } })) as Promise<Page>,`).join('')}${related.length ? '\n    ' : ''}},
  },`);
  }
  const lists = model.lists.map((l) => `\n    ${lit(l.id)}: (query) => call(client.GET(${lit(`/api/list/${l.id}`)}, { params: { query: query as Q<${lit(`/api/list/${l.id}`)}> } })) as Promise<Page>,`).join('');
  const dashboards = model.dashboards.map((d) => `\n    ${lit(d.id)}: (query) => call(client.GET(${lit(`/api/dashboard/${d.id}`)}, { params: { query: query as Q<${lit(`/api/dashboard/${d.id}`)}> } })) as Promise<Dashboard>,`).join('');
  const actions = model.globalActions.filter((a) => has(`/api/action/${a.name}`, 'post')).map((a) => `\n    ${lit(a.name)}: (body) => call(client.POST(${lit(`/api/action/${a.name}`)}, { body: body as B<${lit(`/api/action/${a.name}`)}> })) as Promise<{ ok: true; flash: string; created?: number }>,`).join('');
  const session = model.roles ? `
  login: (body) => call(client.POST('/api/login', { body })) as Promise<Signed>,
  logout: () => call(client.POST('/api/logout', { body: {} })) as Promise<Signed>,
  register: (body) => ${has('/api/register', 'post') ? `call(client.POST('/api/register', { body: body as B<'/api/register'> })) as Promise<Signed>` : `Promise.reject(new ApiError(404, ['Registration is closed.']))`},` : `
  login: () => Promise.reject(new ApiError(404, ['This app has no sign-in.'])),
  logout: () => Promise.reject(new ApiError(404, ['This app has no sign-in.'])),
  register: () => Promise.reject(new ApiError(404, ['This app has no sign-in.'])),`;
  return `${HEADER}import type { paths } from '@/gen/api';
import { ApiError, call, client, type AppEndpoints, type Dashboard, type Page, type Row, type Saved, type Signed } from '@/lib/api';

// The query of a GET and the JSON body of a POST, as the contract declares them.
type Q<P extends keyof paths> = paths[P] extends { get: { parameters: { query?: infer T } } } ? T : never;
type B<P extends keyof paths> = paths[P] extends { post: { requestBody: { content: { 'application/json': infer T } } } } ? T : never;

void ApiError;

export const endpoints: AppEndpoints = {
  entities: {
${lines.map((l) => l.replace(/^/gm, '  ')).join('\n')}
  },
  lists: {${lists}${lists ? '\n  ' : ''}},
  dashboards: {${dashboards}${dashboards ? '\n  ' : ''}},
  actions: {${actions}${actions ? '\n  ' : ''}},
  me: () => call(client.GET('/api/me')) as Promise<{ user: Row | null; role: string | null }>,${session}
};
`;
}

const ident = (s) => s.replace(/[^A-Za-z0-9]/g, '_');

function routesTsx(model) {
  const routes = [];
  const add = (name, path, element, search) => routes.push({ name, path, element, search });
  for (const e of Object.values(model.entities)) {
    const n = ident(e.name);
    add(`${n}List`, `/${e.name}`, `<EntityListScreen entity=${lit(e.name)} />`, true);
    add(`${n}New`, `/${e.name}/new`, `<FormScreen entity=${lit(e.name)} mode="new" />`);
    add(`${n}Detail`, `/${e.name}/$id`, `<DetailScreen entity=${lit(e.name)} />`);
    add(`${n}Edit`, `/${e.name}/$id/edit`, `<FormScreen entity=${lit(e.name)} mode="edit" />`);
  }
  for (const l of model.lists) add(`list_${ident(l.id)}`, `/list/${l.id}`, `<SavedListScreen id=${lit(l.id)} />`, true);
  for (const d of model.dashboards) add(`dashboard_${ident(d.id)}`, `/dashboard/${d.id}`, `<Suspense fallback={<Skeleton className="h-96 w-full" />}><DashboardScreen id=${lit(d.id)} /></Suspense>`, true);
  for (const p of model.pages) add(`page_${ident(p.id)}`, `/page/${p.id}`, `<PageScreen id=${lit(p.id)} />`);
  if (model.roles) {
    add('login', '/login', '<LoginScreen />', true);
    if (model.roles.register) add('register', '/register', '<RegisterScreen />');
  }
  const home = model.home || model.nav[0]?.to || null;
  const imports = [
    model.dashboards.length ? `import { lazy, Suspense } from 'react';` : null,
    `import { createRootRoute, createRoute, createRouter, redirect } from '@tanstack/react-router';`,
    `import { AppShell } from '@/components/app-shell';`,
    `import { NotFound } from '@/components/states';`,
    `import { EntityListScreen, SavedListScreen } from '@/screens/list-screen';`,
    `import { DetailScreen } from '@/screens/detail-screen';`,
    `import { FormScreen } from '@/screens/form-screen';`,
    // The charts library only loads with the first dashboard opened.
    model.dashboards.length ? `import { Skeleton } from '@/components/ui/skeleton';` : null,
    model.pages.length ? `import { PageScreen } from '@/screens/page-screen';` : null,
    model.roles ? `import { LoginScreen${model.roles.register ? ', RegisterScreen' : ''} } from '@/screens/auth-screens';` : null,
  ].filter(Boolean);
  // The charts library loads with the first dashboard opened, not with the app.
  const lazies = model.dashboards.length ? ["const DashboardScreen = lazy(() => import('@/screens/dashboard-screen').then((m) => ({ default: m.DashboardScreen })));"] : [];
  const body = routes.map((r) => `const ${r.name} = createRoute({ getParentRoute: () => root, path: ${lit(r.path)},${r.search ? ' validateSearch: keep,' : ''} component: () => ${r.element} });`);
  return `${HEADER}${imports.join('\n')}
${lazies.length ? `\n${lazies.join('\n')}\n` : ''}
// Search parameters stay as the URL has them; each screen reads the ones it knows.
const keep = (s: Record<string, unknown>) => s;

const root = createRootRoute({ component: AppShell, notFoundComponent: () => <NotFound /> });
const index = createRoute({ getParentRoute: () => root, path: '/', beforeLoad: () => { ${home ? `throw redirect({ to: ${lit(home)}, replace: true });` : ''} }, component: () => <NotFound /> });
${body.join('\n')}

const tree = root.addChildren([index, ${routes.map((r) => r.name).join(', ')}]);

export const router = createRouter({ routeTree: tree, defaultPreload: 'intent', scrollRestoration: true, defaultNotFoundComponent: () => <NotFound /> });
`;
}

function readme(model) {
  return `# ${model.title}: the generated front end

Generated by \`webgen\` from \`apps/${model.name}/app.json\` and its OpenAPI contract (\`openapi.json\`, the snapshot
this generation read). Every screen comes from the graph: do not edit the files here, change the graph and generate
again:

\`\`\`bash
node webgen/gen.mjs apps/${model.name}/app.json --openapi apps/${model.name}/web/openapi.json --out apps/${model.name}/web
cd apps/${model.name}/web && npm ci && npm run build      # dist/ is what the runtime serves at /
npm run check:contract                                     # the snapshot and the types still match the runtime
CANOPY_API=http://127.0.0.1:8901 npm run dev               # against a running app (node runtime/run.mjs … --port 8901)
\`\`\`

- \`src/gen/\` — generated per app: \`app.ts\` (the model of the graph), \`api.d.ts\` (openapi-typescript),
  \`endpoints.ts\` (typed openapi-fetch calls), \`routes.tsx\` (TanStack Router), \`theme.css\` (the graph's theme).
- everything else is webgen's template: the design system (shadcn/ui on Radix and Tailwind) and the screens.
`;
}

/**
 * Every file of the generated project except the template: path → text.
 * @param {any} model the app model (lib/model.mjs) @param {any} openapi the contract @param {string} types src/gen/api.d.ts
 */
export function emit(model, openapi, types) {
  return new Map([
    ['package.json', packageJson(model)],
    ['index.html', indexHtml(model)],
    ['README.md', readme(model)],
    ['openapi.json', json(openapi)],
    ['src/gen/app.ts', appTs(model)],
    ['src/gen/api.d.ts', types],
    ['src/gen/endpoints.ts', endpointsTs(model, openapi)],
    ['src/gen/routes.tsx', routesTsx(model)],
    ['src/gen/theme.css', themeCss(model)],
  ]);
}
